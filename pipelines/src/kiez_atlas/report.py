"""Generate the Phase 1 classification report from the built data.

Generated, not hand-written: every number is read from data/internal/*, so the
report cannot drift away from the data it describes.
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path

RULE_LABEL = {
    "R1": "non-physical resource",
    "R2": "inherently public venue type",
    "R3": "funding body / bank / state office, no public-access evidence",
    "R3b": "association or advice desk, only weak function evidence",
    "R4": "strong public-access evidence overrode the category default",
    "R5": "physical, public access not evidenced",
    "R6": "unmapped",
}


def _md_table(rows, headers):
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def generate(repo: Path) -> str:
    inv = json.loads((repo / "data/internal/venue_inventory.json")
                     .read_text(encoding="utf-8"))
    review = json.loads((repo / "data/internal/review_queue.json")
                        .read_text(encoding="utf-8"))
    meta = json.loads((repo / "data/public/metadata.json")
                      .read_text(encoding="utf-8"))
    v = inv["venues"]

    status = Counter(x["classification"]["product_status"] for x in v)
    types = Counter(x["classification"]["venue_type"] for x in v)
    rules = Counter(x["classification"]["rule"] for x in v)
    inc_types = Counter(x["classification"]["venue_type"] for x in v
                        if x["classification"]["product_status"] == "included")
    rev_types = Counter(x["classification"]["venue_type"] for x in v
                        if x["classification"]["product_status"] == "pending_review")

    physical = [x for x in v if x["classification"]["venue_type"] != "portal"]
    non_physical = [x for x in v if x["classification"]["venue_type"] == "portal"]

    L = []
    L.append("# Phase 1 — Venue Classification Report")
    L.append("")
    L.append(f"**Generated {inv['generated_at']} from `data/internal/venue_inventory.json`. "
             "This file is generated by `pipelines/src/kiez_atlas/report.py`; do not edit "
             "the numbers by hand.**")
    L.append("")
    L.append("Scope decision applied: the Atlas is a broad network of community-relevant "
             "**physical** venues, defined by community function — not by the inherited "
             "directory category, and not limited to `cat: \"hub\"`.")
    L.append("")

    # ---------------- headline ----------------
    L.append("## 1. Headline counts")
    L.append("")
    L.append(_md_table([
        ("Original records preserved", len(v), "All 303 kept in the internal inventory, none deleted."),
        ("Physical venues", len(physical), "Every record except the one online portal."),
        ("Portals / non-physical entries", len(non_physical),
         "Excluded by rule R1."),
        ("**Included** in the directory", status["included"], "Published in `data/public/venues.json`."),
        ("**Excluded**", status["excluded"], "Kept in the inventory with a reason."),
        ("**Pending review**", status["pending_review"], "In `data/internal/review_queue.json`."),
    ], ["Measure", "Count", "Note"]))
    L.append("")
    L.append(f"251 + 9 + 43 = {status['included'] + status['excluded'] + status['pending_review']} — "
             "the three statuses partition all 303 records exactly.")
    L.append("")

    # ---------------- rules ----------------
    L.append("## 2. Which rule decided each record")
    L.append("")
    L.append(_md_table([(k, RULE_LABEL[k], rules[k]) for k in sorted(rules)],
                       ["Rule", "Meaning", "Records"]))
    L.append("")
    L.append("Rules are evaluated in order R1 → R2 → R4 → R3 → R3b → R5 → R6, first match "
             "wins. R4 (strong public-access evidence) deliberately outranks R3/R3b/R5, so "
             "an advice desk or studio house that demonstrably serves the public is included "
             "despite its category.")
    L.append("")

    # ---------------- type distribution ----------------
    L.append("## 3. Distribution by venue type")
    L.append("")
    L.append(_md_table([(t, n, inc_types.get(t, 0), rev_types.get(t, 0),
                         n - inc_types.get(t, 0) - rev_types.get(t, 0))
                        for t, n in sorted(types.items(), key=lambda kv: (-kv[1], kv[0]))],
                       ["venue_type", "total", "included", "pending_review", "excluded"]))
    L.append("")

    # ---------------- excluded ----------------
    L.append("## 4. Every exclusion, with its reason")
    L.append("")
    L.append("Nothing is excluded silently. Each row is the rule's own stated reason.")
    L.append("")
    ex_rows = []
    for x in v:
        c = x["classification"]
        if c["product_status"] == "excluded":
            ex_rows.append((x["venue_name"][:58], c["venue_type"], c["rule"],
                            x["inherited"]["desc"][:110].replace("|", "/")))
    L.append(_md_table(ex_rows, ["Venue", "Type", "Rule", "Record evidence"]))
    L.append("")
    L.append("The eight R3 exclusions are funding institutions, a state development bank, two "
             "senatorial departments and one university unit. Their function is to *allocate* "
             "resources, not to host public community activity. They remain valuable to the "
             "CCI Atlas itself — they are excluded from the **event** directory only.")
    L.append("")
    L.append("The single R1 exclusion, Creative City Berlin, is described in the source data as "
             "an \"Online community portal\" and its address is a `c/o` for another "
             "organisation — a postal address, not a public venue.")
    L.append("")

    # ---------------- review ----------------
    L.append(f"## 5. Pending review — {status['pending_review']} records")
    L.append("")
    L.append("These are **not** undecided due to laziness. They are cases where the record "
             "genuinely does not settle the question, and the decision forbids making a "
             "subjective call silently. Each needs one of three outcomes from you: promote to "
             "`included`, demote to `excluded`, or supply evidence.")
    L.append("")
    grouped = defaultdict(list)
    for r in review["venues"]:
        grouped[r["venue_type"]].append(r)
    for t in sorted(grouped, key=lambda k: -len(grouped[k])):
        rs = grouped[t]
        L.append(f"### {t} — {len(rs)} records")
        L.append("")
        if t == "artist_studio_building":
            L.append("Artist studio houses. They are physical and culturally vital, but the "
                     "record evidences *studio letting*, not public access. Several do run open "
                     "studios or exhibitions — those were promoted by rule R4 (see "
                     "Atelierhaus Mengerzeile). The remaining question is factual, not "
                     "philosophical: does this building hold public programmes?")
        elif t == "advice_centre":
            L.append("Advice and service desks. Most are appointment-based professional "
                     "services, which the inclusion policy excludes (formal/professional "
                     "support, not public community activity). Music Pool Berlin was promoted "
                     "because its record states *free one-hour consultations*.")
        elif t == "association_office":
            L.append("Membership associations and professional chambers. Being *about* a scene "
                     "is not hosting that scene's events. This group is where the earlier "
                     "false positives came from, so it is deliberately quarantined for review "
                     "rather than guessed.")
        elif t == "rehearsal_space":
            L.append("Rehearsal spaces: hire-only by the hour in these two cases.")
        elif t == "coworking_space":
            L.append("Commercial coworking. Both mention event space, but neither record "
                     "establishes a public programme.")
        L.append("")
        L.append(_md_table([(r["venue_name"][:56], r["inherited_cat"], r["rule"],
                            r["address"][:34]) for r in rs],
                           ["Venue", "inherited cat", "Rule", "Address"]))
        L.append("")

    # ---------------- evidence for ambiguous ----------------
    L.append("## 6. Evidence behind the ambiguous decisions")
    L.append("")
    L.append("Two evidence tiers exist because a single matcher produced demonstrably wrong "
             "answers during development:")
    L.append("")
    L.append("- **STRONG** — an explicit public-access construction (`open to the public`, "
             "`free consultations`, `drop-in`, `open studio`, `Veranstaltungen`). Sufficient "
             "to include.")
    L.append("- **WEAK** — a venue-function hint that does not establish access "
             "(`exhibition`, `workshop`, `courses`, `theatre`). Sufficient only to route to "
             "review, never to include.")
    L.append("")
    L.append("Two concrete false positives the tiers were built to stop:")
    L.append("")
    L.append("| Record | Why a naive matcher included it | Correct outcome |")
    L.append("|---|---|---|")
    L.append("| IBB Ventures – VC Fonds Kreativwirtschaft | `early-stage` matched `stage`, and "
             "`public venture capital arm` matched a public-* construction | excluded (R3) |")
    L.append("| LAFT Berlin; Bundesverband Freie Darstellende Künste | descriptions contain "
             "`theatre` — they are *about* theatre, they do not host it | pending_review (R3b) |")
    L.append("")
    L.append("Both are now pinned by regression tests in `pipelines/tests/test_classify.py`.")
    L.append("")
    L.append("A third bug was found by reviewing the totals rather than the rules: type "
             "patterns matched the **description**, so 12 public libraries that merely mention "
             "a makerspace they host were retyped as makerspaces. Types are now derived from "
             "the **name** only — a description says what a venue does, not what it is. That "
             "bug was invisible in the status totals (251/9/43 unchanged) and only surfaced "
             "because the type distribution was checked against the inherited categories.")
    L.append("")

    # ---------------- independence ----------------
    L.append("## 7. Source status is independent of directory membership")
    L.append("")
    L.append("Per the decision, a venue qualifies for the directory even with no event feed "
             "discovered. All 303 inventory records currently carry "
             "`event_source_status: \"not_assessed\"`, and a validation check asserts that no "
             "other value has been written at Phase 1 — so membership provably cannot have "
             "been influenced by source availability.")
    L.append("")

    # ---------------- geography ----------------
    g = meta["geography"]
    L.append("## 8. Geography preserved")
    L.append("")
    L.append(_md_table([
        ("Bezirksregionen published", meta["counts"]["bezirksregionen"]),
        ("Planungsräume available", meta["counts"]["planning_raeume"]),
        ("Bezirksregionen with ≥1 included venue", meta["counts"]["bezirksregionen_with_venues"]),
        ("Venues whose point-in-polygon LOR agrees with the Atlas value",
         g["lor_agrees_with_atlas"]),
        ("Disagreements preserved for audit (not overwritten)",
         len(g["lor_disagreements"])),
    ], ["Measure", "Value"]))
    L.append("")
    L.append("Both the Atlas's own `lor` and the independently computed point-in-polygon result "
             "are stored per record. The Atlas value is not silently replaced: its assignment "
             "may use address knowledge a coordinate does not have.")
    L.append("")
    L.append("Non-unique Bezirksregion names are recorded in `metadata.json` so the join-on-id "
             "rule is explicit: " + json.dumps(g["duplicate_bzr_names"], ensure_ascii=False) + ".")
    L.append("")

    # ---------------- attribution ----------------
    L.append("## 9. Attribution and provenance")
    L.append("")
    L.append("- Every inventory record keeps the original `src` as `provenance.source_reference`, "
             "and every public venue keeps it in `atlas_provenance`. A validation check compares "
             "all 12 inherited fields per record against `index.html` and fails on any drift.")
    L.append("- The inherited source register (7 entries) is carried through unchanged in "
             "`metadata.json`.")
    L.append("- **The LOR geography is credited nowhere in the inherited project.** This "
             "pipeline adds a proposed attribution entry with the vintage recorded as "
             "`\"unknown\"` rather than guessed. Confirming it with the upstream controller is "
             "an open action, and the licence question in the feasibility report (§G.4, Q2) "
             "still gates republication.")
    L.append("")

    # ---------------- websites ----------------
    L.append("## 9b. What a `website` value means")
    L.append("")
    L.append("The inherited `PLACES[].url` is **not** a verified official website. It is a "
             "page the compiler used to describe the venue. Audited across all 303 records:")
    L.append("")
    wk = Counter(x["website_assessment"]["kind"] for x in v)
    wpub = Counter(intf["website"]["kind"] for intf in
                   json.loads((repo / "data/public/venues.json")
                              .read_text(encoding="utf-8"))["venues"])
    L.append(_md_table(
        [(k, desc, wk.get(k, 0), wpub.get(k, 0))
         for k, desc in [
             ("directory_reference",
              "third-party listing/portal, not the venue's own site"),
             ("shared_organisation_site",
              "one URL reused by several venues under an umbrella organisation"),
             ("venue_site_unverified",
              "domain that appears to belong to the venue; not visited"),
         ]],
        ["kind", "meaning", "all 303", "published"]))
    L.append("")
    n_pub = sum(wpub.values())
    L.append(f"**No record is labelled official.** `verification` is `unverified` for all "
             f"{n_pub} published records, and `metadata.websites.official_claims` is "
             f"{meta['websites']['official_claims']}. The strongest claim the data supports is "
             "\"this domain appears to belong to the venue\" — the feasibility phase never "
             "visited these sites.")
    L.append("")
    L.append("The most misleading case: **19 studio houses share one "
             "`bbk-kulturwerk.de/en/art-spaces-berlin/studio-houses` page** (16 of them are in "
             "the review queue, 3 published). All 19 are `directory_reference`.")
    L.append("")

    # ---------------- lor provisional ----------------
    lor = meta["attribution"]["added_by_this_pipeline"][0]
    L.append("## 9c. LOR attribution is provisional, and says so")
    L.append("")
    L.append(_md_table([
        ("status", lor.get("status")),
        ("vintage", lor.get("vintage")),
        ("licence", lor.get("licence")),
        ("blocks_publication", lor.get("blocks_publication")),
        ("confirmation_required_from", lor.get("confirmation_required_from")),
    ], ["field", "value"]))
    L.append("")
    L.append("The inherited project credits the LOR geography **nowhere**, so this pipeline "
             "adds an entry. It is marked `provisional` because both the source vintage and "
             "the licence are unknown. `metadata.attribution.publication_blockers` names it "
             "explicitly, and a validation check fails if the status is ever silently "
             "promoted to confirmed.")
    L.append("")

    # ---------------- deploy boundary ----------------
    L.append("## 9d. Public / internal boundary is enforced, not promised")
    L.append("")
    L.append("Two guards in `pipelines/src/kiez_atlas/deploy.py`, both exercised by tests "
             "and by validation checks:")
    L.append("")
    L.append("1. `resolve_deploy_set()` expands `data/deploy-allowlist.txt` and refuses any "
             "path that: does not exist, escapes the repository, lives under `data/internal/`, "
             "or matches a forbidden filename.")
    L.append("2. `assert_no_internal_leak(staged)` inspects a **staged output directory** and "
             "fails if any internal artefact is present. It judges the output, not the "
             "intention, so a misconfigured copy step is caught even when the allowlist looks "
             "correct.")
    L.append("")
    L.append("Proven behaviour: staging `data/public/` passes; staging all of `data/` is "
             "refused; copying a single `review_queue.json` into a staging directory is "
             "caught.")
    L.append("")

    # ---------------- limits ----------------
    L.append("## 10. Honest limits of this classification")
    L.append("")
    L.append("1. **Classification is derived from the inherited English descriptions, not from "
             "visiting the venues.** Where a description is thin, the record went to review "
             "rather than being guessed — but a confident wrong description yields a confident "
             "wrong classification.")
    L.append("2. **No venue was verified as currently open or at that address.** One Atlas URL "
             "was already 404 during the feasibility study (kiekin.org), so link rot exists in "
             "the source data.")
    L.append("3. **The 251 included venues are included on the strength of their venue type, "
             "not on evidence of actual community programming.** 249 of them were decided by "
             "R2 — \"a library/community centre is public infrastructure\". That is a "
             "reasonable default and it is not the same thing as evidence.")
    L.append("4. **Community kitchens and urban gardens are not represented as types.** The "
             "decision names them, but the 303 records contain no venue whose primary function "
             "is either; two mention a garden or kitchen as an amenity. Adding those types now "
             "would create empty categories. The vocabulary is designed so they can be added "
             "later without a data-model change, and a test asserts exactly that.")
    L.append("5. **`flag` semantics remain undocumented** (feasibility report Q3), so no price "
             "or access inference was drawn from it.")
    L.append("")
    L.append("## 11. What I need from you")
    L.append("")
    L.append("| # | Decision | Where |")
    L.append("|---|---|---|")
    L.append("| 1 | Artist studio houses (16): include as cultural venues, or require evidence "
             "of public programmes? | `review_queue.json` |")
    L.append("| 2 | Advice centres (12): professional advice is out of scope by policy — confirm "
             "the whole group is excluded, not reviewed. | `review_queue.json` |")
    L.append("| 3 | Associations (11): confirm excluded unless they host public events. | "
             "`review_queue.json` |")
    L.append("| 4 | Coworking (2) and hire-only rehearsal (2): exclude? | `review_queue.json` |")
    L.append("| 5 | Is the LOR attribution wording acceptable to send upstream? | "
             "`metadata.json` |")
    L.append("")
    return "\n".join(L) + "\n"


def main() -> int:
    import sys
    repo = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
    out = repo / "docs" / "feasibility" / "CLASSIFICATION_REPORT.md"
    out.write_text(generate(repo), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
